"""git push guard for every worker the centre starts (Claude, Codex, Kiro, metacog).

User rule: never push to a team repository. A project marks its repository in config/projects.local.json
with "team_repo": false (solo, the worker commits and pushes) or true (team, never pushed). A repository
that is unmarked or unregistered counts as a team repository. Force pushes and remote ref deletions are
blocked everywhere.

The guard is a pre-push hook. Workers get it through GIT_CONFIG_* environment variables that point
core.hooksPath at ~/.all-tomorrow/git-hooks, so it works for any CLI that runs git. Because core.hooksPath
replaces the repository's own hooks directory, the other client hooks there just hand off to the
repository's .git/hooks.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

HOOKS_DIR = Path.home() / ".all-tomorrow" / "git-hooks"
REGISTRY = Path(os.environ.get("ALL_TOMORROW_PROJECTS",
                               Path(__file__).resolve().parents[3] / "config" / "projects.local.json"))
SOLO_LIST = "solo-repos.txt"

PRE_PUSH = r"""#!/bin/sh
# Generated by all_tomorrow.adapters.push_guard. Solo repositories only, no force push, no remote ref deletion.
top=$(git rev-parse --show-toplevel | tr 'A-Z\\' 'a-z/') || exit 1
if ! grep -Fxq -- "$top" "$(dirname "$0")/solo-repos.txt" 2>/dev/null; then
  echo "push guard: $top is a team repository or not marked solo (team_repo: false in projects.local.json); push blocked" >&2
  exit 1
fi
refs=$(cat)
zero=0000000000000000000000000000000000000000
while read -r lref lsha rref rsha; do
  [ -n "$lref" ] || continue
  if [ "$lsha" = "$zero" ]; then echo "push guard: deleting $rref is blocked" >&2; exit 1; fi
  if [ "$rsha" != "$zero" ] && ! git merge-base --is-ancestor "$rsha" "$lsha" 2>/dev/null; then
    echo "push guard: force push to $rref is blocked" >&2; exit 1
  fi
done <<EOF
$refs
EOF
own="$(git rev-parse --git-common-dir)/hooks/pre-push"
if [ -x "$own" ]; then printf '%s\n' "$refs" | "$own" "$@"; exit $?; fi
exit 0
"""

# Client hooks a repository may define itself; they keep working while core.hooksPath points here.
CHAINED = ("applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit", "pre-merge-commit",
           "prepare-commit-msg", "commit-msg", "post-commit", "pre-rebase", "post-checkout", "post-merge",
           "post-rewrite", "pre-auto-gc", "post-index-change")
CHAIN = """#!/bin/sh
own="$(git rev-parse --git-common-dir)/hooks/{name}"
[ -x "$own" ] && exec "$own" "$@"
exit 0
"""


def solo_repos(registry: Path | None = None) -> list[str]:
    """Lower-cased forward-slash paths of projects marked "team_repo": false."""
    try:
        projects = json.loads((registry or REGISTRY).read_text(encoding="utf-8-sig")).get("projects", {})
    except (OSError, ValueError):
        return []
    return sorted({str(p["path"]).replace("\\", "/").rstrip("/").lower()
                   for p in projects.values() if p.get("team_repo") is False and p.get("path")})


def _write(path: Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def install(hooks_dir: Path | None = None, registry: Path | None = None) -> Path:
    hooks = hooks_dir or HOOKS_DIR
    hooks.mkdir(parents=True, exist_ok=True)
    _write(hooks / "pre-push", PRE_PUSH)
    for name in CHAINED:
        _write(hooks / name, CHAIN.format(name=name))
    _write(hooks / SOLO_LIST, "".join(f"{p}\n" for p in solo_repos(registry)))
    return hooks


def git_environment(base: dict[str, str], hooks_dir: Path | None = None,
                    registry: Path | None = None) -> dict[str, str]:
    """GIT_CONFIG_* entries that add core.hooksPath on top of any the environment already carries.
    An install error propagates: a worker without the guard must not start."""
    hooks = install(hooks_dir, registry)
    try:
        count = int(base.get("GIT_CONFIG_COUNT", "0"))
    except ValueError:
        count = 0
    return {"GIT_CONFIG_COUNT": str(count + 1), f"GIT_CONFIG_KEY_{count}": "core.hooksPath",
            f"GIT_CONFIG_VALUE_{count}": hooks.as_posix()}
