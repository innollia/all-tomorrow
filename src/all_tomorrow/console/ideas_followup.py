def split_prompt(idea: dict[str, Any], questions: list[str], start: int) -> str:
    """사용자의 추가 질문을 자기완결 하위 프롬프트 S{start}…로 나누라는 자료봉 요청. 과제는 처음 쪼개기와 같은 결과 블록으로 돌아온다."""
    decided = re.search(r"^#{1,6}\s*정해진 것[^\n]*\n(.*?)(?=^#{1,6}\s|\Z)", idea.get("synth", ""), re.S | re.M)
    return SPLIT.format(start=start, idea_id=idea["id"], questions="\n".join("- " + q for q in questions),
                        decided=decided.group(1).strip() if decided else "없음", context=build_context(idea))


def material_item(request: str, output: str, run_id: str) -> dict[str, Any]:
    """조사 결과를 아이디어 자유 자료로 넣을 항목(ideas_intake의 항목과 같은 모양)."""
    request = request.strip()
    return {"kind": "paste", "label": LABEL, "url": "", "title": "추가 조사: " + _clip(request, 40),
            "body": output.strip(), "note": f"요청 원문: {_clip(request, 300)} · 실행 {run_id}"}


